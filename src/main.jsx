import React from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import './index.css';
import App from './App.jsx';
import { AdminProvider } from './context/Auth.jsx';
import { ReasonProvider } from './components/Reason.jsx';
const qc = new QueryClient({ defaultOptions: { queries: { staleTime: 30_000, refetchOnWindowFocus: false, retry: (n, e) => !(e?.status >= 400 && e?.status < 500) && n < 2 } } });
createRoot(document.getElementById('root')).render(<QueryClientProvider client={qc}><BrowserRouter><AdminProvider><ReasonProvider><App /></ReasonProvider></AdminProvider></BrowserRouter></QueryClientProvider>);
